"""Generate tracker/trk_tables.h: the token-class table of the C tracker, from a vocab list
(corpus/vocab.json format: index = token id, entry = uppercase token hex, ids 0-3 specials).
A different vocab regenerates the table; the tracker's code does not change.

    uv run python -m tracker.gen_tables [--vocab corpus/vocab.json] [-o tracker/trk_tables.h]
    uv run python -m tracker.gen_tables --vocab runs/v1/export/model.json   # its "vocab" list

Classes (one byte per token id):
    0..36     name characters A-Z, 0-9, theta (the class is the name index)
    STR0+k    Str token AA00+k        MAT0+k   matrix token 5C00+k ([A]+k)
    PIC0+n    Pic n (token 6000 is Pic1, 6009 is Pic0)   GDB0+n   GDB n (same order)
    SYSLIST   L1-L6 (always exist)
    OTHER     everything else, including <unk>
    LPAREN..FUNC  tokens that open a parenthesis (contiguous range)
"""
from __future__ import annotations

import argparse
import json
from functools import lru_cache
from pathlib import Path

HERE = Path(__file__).resolve().parent
VOCAB = HERE.parent / "corpus" / "vocab.json"
OUT = HERE / "trk_tables.h"

_ORDER = (["STR0"] + [None] * 9 + ["MAT0"] + [None] * 9 + ["PIC0"] + [None] * 9 + ["GDB0"]
          + [None] * 9 + ["SYSLIST", "OTHER", "NEWLINE", "COLON", "QUOTE", "STORE", "COMMA",
                          "RPAREN", "RBRACE", "RBRACKET", "LBRACE", "LBRACKET", "IF", "THEN",
                          "ELSE", "END", "WHILE", "REPEAT", "LBL", "GOTO", "LISTL", "PRGM",
                          "DELVAR", "INPUT", "PROMPT", "SETUPED", "STOREPIC", "RECALLPIC",
                          "STOREGDB", "RECALLGDB", "BOS", "EOS", "PAD", "STATVAR", "STATCMD",
                          # openers: keep contiguous and last
                          "LPAREN", "FOR", "MENU", "ISDS", "DIM", "EQUSTR", "LISTMATR",
                          "MATRLIST", "STATOPEN", "FUNC"])
CLASSES: dict[str, int] = {name: 37 + i for i, name in enumerate(_ORDER) if name}
OPENERS = ("LPAREN", "FOR", "MENU", "ISDS", "DIM", "EQUSTR", "LISTMATR", "MATRLIST", "STATOPEN",
           "FUNC")
# statistics result variables: ERR:UNDEFINED in a clean state (probe_os.py ST62xx), except
# 6221 (sequence n), until a statistics command (STATCMD / STATOPEN) has run
STAT_VARS = {f"62{k:02X}" for k in range(0x01, 0x3D)} - {"6221"}
STAT_CMDS = {"F2", "F3", "F4", "F5", "F6", "F7", "F8", "F9", "FF", "2E", "2F", "BB32", "BB33",
             "BB34", "BB3C", "BB41", "BB46", "BB47", "BB48", "BB49", "EF15",
             # these end in "(" and open a parenthesis too
             "BB3B", "BB3D", "BB3E", "BB3F", "BB40", "BB42", "BB43", "BB44", "BB59", "EF14"}

BY_HEX = {
    "3F": "NEWLINE", "3E": "COLON", "2A": "QUOTE", "04": "STORE", "2B": "COMMA",
    "11": "RPAREN", "09": "RBRACE", "07": "RBRACKET", "08": "LBRACE", "06": "LBRACKET",
    "CE": "IF", "CF": "THEN", "D0": "ELSE", "D4": "END", "D1": "WHILE", "D2": "REPEAT",
    "D6": "LBL", "D7": "GOTO", "EB": "LISTL", "5F": "PRGM", "BB54": "DELVAR", "DC": "INPUT",
    "DD": "PROMPT", "BB4A": "SETUPED", "98": "STOREPIC", "99": "RECALLPIC", "9A": "STOREGDB",
    "9B": "RECALLGDB", "10": "LPAREN", "D3": "FOR", "E6": "MENU", "DA": "ISDS", "DB": "ISDS",
    "B5": "DIM", "BB55": "EQUSTR", "BB3A": "LISTMATR", "BB39": "MATRLIST",
}
NAME_HEX = [f"{c:02X}" for c in range(0x41, 0x5B)] + [f"{c:02X}" for c in range(0x30, 0x3A)] \
    + ["5B"]


@lru_cache(maxsize=1)
def display_names() -> dict[str, str]:
    from tivars.models import TI_84PCE

    return {b.hex().upper(): t.langs["en"].display for b, t in TI_84PCE.tokens.bytes.items()}


def token_class(hx: str, names: dict[str, str]) -> int:
    specials = {"<pad>": "PAD", "<bos>": "BOS", "<eos>": "EOS", "<unk>": "OTHER"}
    if hx in specials:
        return CLASSES[specials[hx]]
    if hx in NAME_HEX:
        return NAME_HEX.index(hx)
    if hx in BY_HEX:
        return CLASSES[BY_HEX[hx]]
    if hx in STAT_VARS:
        return CLASSES["STATVAR"]
    if hx in STAT_CMDS:
        return CLASSES["STATOPEN" if names.get(hx, "").endswith("(") else "STATCMD"]
    if len(hx) == 4 and hx[2] == "0":
        low = int(hx[3], 16)
        if hx[:2] == "AA" and low <= 9:
            return CLASSES["STR0"] + low
        if hx[:2] == "5C" and low <= 9:
            return CLASSES["MAT0"] + low
        if hx[:2] == "60" and low <= 9:
            return CLASSES["PIC0"] + (low + 1) % 10
        if hx[:2] == "61" and low <= 9:
            return CLASSES["GDB0"] + (low + 1) % 10
        if hx[:2] == "5D" and low <= 5:
            return CLASSES["SYSLIST"]
    if names.get(hx, "").endswith("("):
        return CLASSES["FUNC"]
    return CLASSES["OTHER"]


def classify(vocab: list[str]) -> list[int]:
    names = display_names()
    return [token_class(hx, names) for hx in vocab]


def render(vocab: list[str]) -> str:
    cls = classify(vocab)
    lines = ["/* Generated by tracker/gen_tables.py from the vocab list: do not edit. */",
             "#ifndef TRK_TABLES_H", "#define TRK_TABLES_H", "",
             f"#define TRK_VOCAB {len(vocab)}", "",
             "/* token classes (0..36 = name characters A-Z 0-9 theta) */"]
    lines += [f"#define CL_{name} {code}" for name, code in CLASSES.items()]
    lines += [f"#define CL_OPEN_FIRST {CLASSES[OPENERS[0]]}",
              f"#define CL_OPEN_LAST {CLASSES[OPENERS[-1]]}", "",
              "static const unsigned char TRK_CLASS[TRK_VOCAB] = {"]
    for i in range(0, len(cls), 16):
        lines.append("    " + ", ".join(f"{c:3d}" for c in cls[i:i + 16]) + ",")
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--vocab", default=str(VOCAB))
    p.add_argument("-o", "--out", default=str(OUT))
    a = p.parse_args(argv)
    vocab = json.loads(Path(a.vocab).read_text())
    if isinstance(vocab, dict):                  # an export's model.json embeds the list
        vocab = vocab["vocab"]
    Path(a.out).write_text(render(vocab))
    print(f"wrote {a.out}: {len(vocab)} token classes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
