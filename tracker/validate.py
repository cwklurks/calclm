"""T4: tracker predictions vs actual TI-OS outcomes on programs already run in CEmu.

    uv run python -m tracker.validate              # report -> eval/runs/w2-t4/report.md

Sets (token ids + the eval harness's results.jsonl for the same programs, same order):
    val-trim   held-out val programs cut to 256 tokens at a line end (eval/runs/val1-trim)
    val-full   the same val programs uncut (eval/runs/w2-val-full, run for this report)
    gen-v1     960 programs generated by CalcLM v1, cut likewise (eval/runs/v1-trim)

For each program the Python spec tracker (identical to the C tracker, T2) reads
<bos> body <eos> and its end state is compared with the outcome:
    unresolved label at end        vs ERR:LABEL     (requirement: every ERR:LABEL has one)
    read of an unassigned list/Str/matrix/Pic/GDB  vs ERR:UNDEFINED (also prgm calls, which
                                   are always missing when a program runs alone)
    unclosed blocks at end         vs outcome       (TI-OS ignores them: tracker/probe_os.py)
    structure errors (stray Then/Else, extra End, malformed label or list names)
                                   vs ERR:SYNTAX
An error "matches" when a tracker event lies on the line the OS reported (2:Goto cursor).
eval/driver.locate_error reads that cursor after a fixed 500 ms, which stops short on long
programs; when tracker/relocate.py has re-run a set's ERR programs with a patient locator
(eval/runs/w2-<set>-loc/), those positions are used instead.
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

import numpy as np

from eval.tokens import line_at
from . import spec

ROOT = Path(__file__).resolve().parent.parent
RUNS = ROOT / "eval" / "runs"
OUT = RUNS / "w2-t4"
SETS = {
    "val-trim": (ROOT / "runs" / "gen" / "val1-trim.jsonl", RUNS / "val1-trim"),
    "val-full": (ROOT / "data" / "tok" / "val.bin", RUNS / "w2-val-full"),
    "gen-v1": (ROOT / "runs" / "gen" / "v1-trim.jsonl", RUNS / "v1-trim"),
}
BOS, EOS, PAD = 1, 2, 0


def load_ids(path: Path) -> list[list[int]]:
    if path.suffix == ".bin":
        stream = np.fromfile(path, dtype="<u2").tolist()
        out, cur = [], []
        for t in stream:
            if t == BOS and cur:
                out.append(cur)
                cur = []
            cur.append(t)
        return out + ([cur] if cur else [])
    rows = [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
    return [r["ids"] if isinstance(r, dict) else r for r in rows]


def analyze(ids: list[int], rec: dict, vocab: list[str]) -> dict:
    """Run the spec tracker over the program the harness ran and relate it to the outcome."""
    body_ids = []
    for t in ids:                                    # as eval/tokens.ids_to_body decodes
        if t == EOS:
            break
        if t not in (BOS, PAD):
            body_ids.append(t)
    tr = spec.Tracker()
    for t in [BOS] + body_ids + [EOS]:
        tr.step(t)
    s, d = tr.summary(), tr.details()
    newline = vocab.index("3F")
    line_of, line = [], 1                            # 1-based line of each body token
    for t in body_ids:
        line_of.append(line)
        if t == newline:
            line += 1
    body = b"".join(bytes.fromhex(vocab[t]) for t in body_ids)
    err_line = None
    if rec.get("error_offset") is not None:
        err_line = line_at(body, rec["error_offset"])[0]

    def lines(kind: str) -> list[int]:
        # an event at the <eos> (a name finished by the end of the program) is on the last line
        return [line_of[min(e[1], len(line_of)) - 1] for e in d["events"]
                if e[0] == kind and e[1] >= 1 and line_of]

    return {"index": rec["index"], "label": rec["label"], "outcome": rec["outcome"],
            "error_line": rec.get("error_line"), "err_line_no": err_line, "sum": s,
            "unres": d["unres"], "undef_lines": lines("undef"), "prgm_lines": lines("prgm"),
            "bad_lines": lines("bad") + lines("extra_end"),
            "undef_events": [e for e in d["events"] if e[0] == "undef"],
            "bad_events": [e for e in d["events"] if e[0] in ("bad", "extra_end")]}


def pct(a: int, b: int) -> str:
    return f"{a}/{b} ({100 * a / b:.1f}%)" if b else "0/0"


def outcome_mix(rows: list[dict]) -> str:
    c = Counter(r["label"] if r["outcome"] == "ERR" else r["outcome"] for r in rows)
    return ", ".join(f"{k} {v}" for k, v in c.most_common(6))


def report_set(name: str, rows: list[dict]) -> tuple[list[str], dict]:
    L: list[str] = [f"### {name} ({len(rows)} programs run)", ""]
    nums: dict = {"n": len(rows)}

    lab = [r for r in rows if r["label"] == "ERR:LABEL"]
    lab_ok = [r for r in lab if r["sum"]["n_unres"] > 0]
    unres = [r for r in rows if r["sum"]["n_unres"] > 0]
    nums.update(err_label=len(lab), err_label_with_unres=len(lab_ok), unres=len(unres),
                unres_err_label=sum(r["label"] == "ERR:LABEL" for r in unres))
    L += ["| check | result |", "|---|---|",
          f"| ERR:LABEL programs with an unresolved label (requirement: all) | "
          f"{pct(len(lab_ok), len(lab))} |",
          f"| programs with an unresolved label that end in ERR:LABEL | "
          f"{pct(nums['unres_err_label'], len(unres))} |"]

    und = [r for r in rows if r["label"] == "ERR:UNDEFINED"]
    on_line = [r for r in und if r["err_line_no"] in r["undef_lines"]]
    prgm_line = [r for r in und if r not in on_line and r["err_line_no"] in r["prgm_lines"]]
    elsewhere = [r for r in und if r not in on_line and r not in prgm_line
                 and (r["undef_lines"] or r["prgm_lines"])]
    unexplained = [r for r in und if not (r["undef_lines"] or r["prgm_lines"])]
    anywhere = [r for r in und if r["undef_lines"] or r["prgm_lines"]]
    rba = [r for r in rows if r["sum"]["n_undef"] > 0]
    rba_und = [r for r in rba if r["label"] == "ERR:UNDEFINED"]
    rba_hit = [r for r in rba_und if r["err_line_no"] in r["undef_lines"]]
    nums.update(err_undef=len(und), undef_anywhere=len(anywhere), undef_on_line=len(on_line),
                undef_prgm_line=len(prgm_line),
                undef_elsewhere=len(elsewhere), undef_unexplained=len(unexplained),
                read_before_assign=len(rba), rba_err_undef=len(rba_und), rba_hit=len(rba_hit))
    L += [f"| ERR:UNDEFINED with a tracker read-before-assign or prgm call anywhere | "
          f"{pct(len(anywhere), len(und))} |",
          f"| ERR:UNDEFINED explained by a tracker read-before-assign on the error line | "
          f"{pct(len(on_line), len(und))} |",
          f"| ERR:UNDEFINED explained by a prgm call on the error line (missing subprogram) | "
          f"{pct(len(prgm_line), len(und))} |",
          f"| ERR:UNDEFINED with tracker events only on other lines | "
          f"{pct(len(elsewhere), len(und))} |",
          f"| ERR:UNDEFINED with no tracker event at all | {pct(len(unexplained), len(und))} |",
          f"| programs with a read-before-assign that end in ERR:UNDEFINED | "
          f"{pct(len(rba_und), len(rba))} |",
          f"| ... with the error on a read-before-assign line | {pct(len(rba_hit), len(rba))} |"]

    syn = [r for r in rows if r["label"] == "ERR:SYNTAX"]
    syn_line = [r for r in syn if r["err_line_no"] in r["bad_lines"]]
    syn_any = [r for r in syn if r["bad_lines"]]
    badp = [r for r in rows if r["bad_lines"]]
    badp_syn = [r for r in badp if r["label"] == "ERR:SYNTAX"]
    nums.update(err_syntax=len(syn), syntax_on_line=len(syn_line), syntax_any=len(syn_any),
                bad=len(badp), bad_err_syntax=len(badp_syn))
    L += [f"| ERR:SYNTAX with a tracker structure error on the error line | "
          f"{pct(len(syn_line), len(syn))} |",
          f"| ERR:SYNTAX with a tracker structure error anywhere | {pct(len(syn_any), len(syn))} |",
          f"| programs with a structure error that end in ERR:SYNTAX | "
          f"{pct(len(badp_syn), len(badp))} |"]

    open_b = [r for r in rows if r["sum"]["depth"] > 0]
    nums.update(unclosed=len(open_b),
                unclosed_err=sum(r["outcome"] == "ERR" for r in open_b),
                closed_err=sum(r["outcome"] == "ERR" for r in rows if r["sum"]["depth"] == 0))
    n_closed = len(rows) - len(open_b)
    L += [f"| programs with unclosed blocks at the end | {pct(len(open_b), len(rows))} |",
          f"| ... ERR rate with unclosed blocks vs without | "
          f"{pct(nums['unclosed_err'], len(open_b))} vs {pct(nums['closed_err'], n_closed)} |",
          ""]
    L += [f"Outcomes of programs with an unresolved label: {outcome_mix(unres)}.", "",
          f"Outcomes of programs with unclosed blocks: {outcome_mix(open_b)}.", ""]

    def ex(title: str, items: list[dict], show) -> None:
        if not items:
            return
        L.append(f"{title} ({len(items)}):")
        L.append("")
        for r in items[:4]:
            L.append(f"- #{r['index']} {r['label']}: {show(r)}")
        L.append("")

    ex("ERR:LABEL without an unresolved label", [r for r in lab if r not in lab_ok],
       lambda r: f"line {r['err_line_no']} `{r['error_line']}`")
    ex("ERR:UNDEFINED with no tracker event", unexplained,
       lambda r: f"line {r['err_line_no']} `{r['error_line']}`")
    ex("ERR:UNDEFINED, tracker events on other lines", elsewhere,
       lambda r: f"line {r['err_line_no']} `{r['error_line']}`; tracker undef lines "
                 f"{r['undef_lines'][:4]}, prgm lines {r['prgm_lines'][:4]}")
    ex("ERR:SYNTAX with no tracker structure error", [r for r in syn if not r["bad_lines"]],
       lambda r: f"line {r['err_line_no']} `{r['error_line']}`")
    ex("Read-before-assign but no ERR:UNDEFINED",
       [r for r in rba if r["label"] != "ERR:UNDEFINED"],
       lambda r: f"first tracker read {r['undef_events'][0][2]} {r['undef_events'][0][3]!r} "
                 f"line {r['undef_lines'][0] if r['undef_lines'] else '?'}")
    return L, nums


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--sets", default=",".join(SETS))
    p.add_argument("--out", default=str(OUT))
    a = p.parse_args(argv)
    vocab = list(spec.default_vocab())
    lines = ["# T4: tracker predictions vs TI-OS outcomes in CEmu", ""]
    allnums = {}
    for name in a.sets.split(","):
        ids_path, run = SETS[name]
        res_path = run / "results.jsonl"
        if not res_path.exists():
            print(f"skip {name}: {res_path} missing", file=sys.stderr)
            continue
        recs = [json.loads(x) for x in res_path.read_text().splitlines() if x.strip()]
        loc_path = RUNS / f"w2-{name}-loc" / "results.jsonl"
        source = "eval/driver.locate_error (500 ms)"
        if loc_path.exists():
            n_loc = 0
            for x in loc_path.read_text().splitlines():
                r = json.loads(x)
                old = recs[r["index"]]
                if r["label"] == old["label"]:
                    n_loc += 1
                    recs[r["index"]] = {**old, **{k: r.get(k) for k in
                                                  ("error_offset", "error_line_no", "error_line")}}
            source = f"tracker/relocate.py ({n_loc} ERR programs re-located)"
        ids = load_ids(ids_path)
        if len(ids) != len(recs):
            raise SystemExit(f"{name}: {len(ids)} programs vs {len(recs)} results")
        rows = [analyze(i, r, vocab) for i, r in zip(ids, recs)
                if r["outcome"] not in ("REJECTED", "HARNESS_ERROR")]
        sec, nums = report_set(name, rows)
        sec.insert(2, f"Error positions: {source}.")
        sec.insert(3, "")
        lines += sec
        allnums[name] = nums
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "report.md").write_text("\n".join(lines) + "\n")
    (out / "numbers.json").write_text(json.dumps(allnums, indent=2) + "\n")
    print("\n".join(lines))
    ok = all(n["err_label"] == n["err_label_with_unres"] for n in allnums.values())
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
