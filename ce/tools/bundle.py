"""Build the CalcLM v2.2 download: dist/CalcLM-v2.2.zip.

    uv run python -m ce.tools.bundle            # after `make` in ce/calclm and the v2 export

The v2.3 release candidate (the wide model shape W) uses the same builder with W's inputs:
`make SHAPE=w`, an export staged by ce.tools.stage_export, its own LD2 fit and INSTALL, and
`--folder CalcLM-v2.3-rc1` (ce/calclm/README.md, v2.3).

One folder, CalcLM-v2.2/, with the program (ce/calclm/bin: CALCLM.8xp, CLMCODE.8xv), the model
(runs/v2/export: CLM00..CLMnn.8xv as model.json plans them, and its CLMVOC.8xv), INSTALL.md
(ce/calclm/INSTALL.md), CLMLD2.8xv generated by make_ld2 from this export and the checked-in
fixture offsets, the two third-party files the v1 download shipped (the CE C libraries
clibs.8xg and arTIfiCE_v2.1.8xp, extracted from that zip into a fresh empty directory and
copied as they are), and SHA256SUMS.txt over all of them. The v1 zip is only read.

Checks before anything is written:
- the core was built for the export's dims (the build directory's clm_shape.h, when present);
- CALCLM.8xp was linked after the core it contains (ce/build/calclm/core.o): rerun `make`
  otherwise;
- CLMCODE.8xv carries the payload the emulator tests attach (ce/build/calclm/clmcode.bin);
- CLMVOC.8xv names this export (blob size and sha256 prefix);
- make_ld2 verifies the full model.bin SHA-256 against model.json and the LD2 fit before
  generating CLMLD2.8xv; no pre-existing offsets AppVar is copied;
- the extras match the checksums of the v1 download's own SHA256SUMS.txt, once each.
The zip is deterministic for unchanged inputs (fixed timestamps, sorted names). Note that `make`
stamps CALCLM.8xp's file header with the build time, so each build changes its checksum.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import tempfile
import zipfile
from pathlib import Path

from ce.calclm.tools.build_flash import appvar_8xv
from ce.calclm.tools.make_ld2 import payload as ld2_payload

ROOT = Path(__file__).resolve().parents[2]
FOLDER = "CalcLM-v2.2"
BUILD = ROOT / "ce" / "build" / "calclm"
LD2_OFFSETS = ROOT / "ce" / "tests" / "fixtures" / "ld2_offsets_full.json"
EXTRAS = ("clibs.8xg", "arTIfiCE_v2.1.8xp")
XV_DATA = 74                       # .8xv: 55-byte file header, 17-byte entry header, 2-byte length
STAMP = (2026, 1, 1, 0, 0, 0)      # fixed zip timestamps: the same inputs give the same bytes
DIR_ATTR = (0o40755 << 16) | 0x10  # drwxr-xr-x + the MS-DOS directory bit (as the v1 zip)
FILE_ATTR = 0o100644 << 16         # -rw-r--r--


class BundleError(Exception):
    pass


def _xv_payload(xv: bytes) -> bytes:
    """An AppVar's data inside a .8xv file (its length field, then the data; a checksum ends
    the file)."""
    return xv[XV_DATA:XV_DATA + int.from_bytes(xv[XV_DATA - 2:XV_DATA], "little")]


def _read(path: Path) -> bytes:
    if not path.is_file():
        raise BundleError(f"missing {path}")
    return path.read_bytes()


def _model_files(export_dir: Path) -> dict[str, bytes]:
    """CLM00..CLMnn.8xv and CLMVOC.8xv; CLMVOC must name this export's blob size."""
    meta = json.loads(_read(export_dir / "model.json"))
    files = {f"{a['name']}.8xv": _read(export_dir / f"{a['name']}.8xv") for a in meta["appvars"]}
    voc = _read(export_dir / "CLMVOC.8xv")
    payload = _xv_payload(voc)
    if (payload[:2] != b"CV" or int.from_bytes(payload[6:9], "little") != meta["blob_bytes"]
            or payload[9:15] != bytes.fromhex(meta["sha256"][:12])):
        raise BundleError(f"CLMVOC.8xv in {export_dir} does not belong to its model.json")
    files["CLMVOC.8xv"] = voc
    return files


def _extras(extras_zip: Path) -> dict[str, bytes]:
    """The extras, by file name, extracted into a fresh empty directory and read back; each
    must appear once and match the checksum in the zip's own SHA256SUMS.txt."""
    out = {}
    with zipfile.ZipFile(extras_zip) as z, tempfile.TemporaryDirectory() as tmp:
        names = [n for n in z.namelist() if not n.endswith("/")]
        sums_member = [n for n in names if Path(n).name == "SHA256SUMS.txt"]
        if len(sums_member) != 1:
            raise BundleError(f"{extras_zip} has no single SHA256SUMS.txt")
        listed = dict(line.split()[::-1] for line in z.read(sums_member[0]).decode().splitlines()
                      if line.strip())
        for name in EXTRAS:
            members = [n for n in names if Path(n).name == name]
            if len(members) != 1:
                raise BundleError(f"{name} is in {extras_zip} {len(members)} times, not once")
            data = Path(z.extract(members[0], tmp)).read_bytes()
            if hashlib.sha256(data).hexdigest() != listed.get(name):
                raise BundleError(f"{name} does not match {extras_zip}'s SHA256SUMS.txt")
            out[name] = data
    return out


def _program_files(program_dir: Path, build_dir: Path | None) -> dict[str, bytes]:
    """CALCLM.8xp and CLMCODE.8xv; with build_dir, both must be the current, tested build."""
    files = {"CALCLM.8xp": _read(program_dir / "CALCLM.8xp"),
             "CLMCODE.8xv": _read(program_dir / "CLMCODE.8xv")}
    if build_dir is not None:
        if (program_dir / "CALCLM.8xp").stat().st_mtime < _stat(build_dir / "core.o"):
            raise BundleError("CALCLM.8xp is older than core.o: run make in ce/calclm")
        if _xv_payload(files["CLMCODE.8xv"]) != _read(build_dir / "clmcode.bin"):
            raise BundleError("CLMCODE.8xv is not the payload the tests attach (clmcode.bin)")
    return files


def _stat(path: Path) -> float:
    if not path.is_file():
        raise BundleError(f"missing {path}")
    return path.stat().st_mtime


def _check_shape(build_dir: Path | None, export_dir: Path) -> None:
    """The core was built for the export's dims (build_core.sh records its shape header)."""
    import re
    shape_h = build_dir / "clm_shape.h" if build_dir is not None else None
    cfg = json.loads(_read(export_dir / "model.json")).get("config")
    if shape_h is None or not shape_h.is_file() or cfg is None:
        return
    dims = dict(re.findall(r"#define (CLM_\w+) (\d+)", shape_h.read_text()))
    want = {"CLM_DIM": cfg["dim"], "CLM_LAYERS": cfg["n_layers"], "CLM_HEADS": cfg["n_heads"],
            "CLM_HIDDEN": cfg["hidden_dim"], "CLM_CTX": cfg["max_seq_len"]}
    if any(int(dims.get(k, -1)) != v for k, v in want.items()):
        raise BundleError(f"the program in {build_dir} was built for another model shape than "
                          f"{export_dir}")


def build_bundle(out: Path, program_dir: Path, export_dir: Path, install_md: Path,
                 extras_zip: Path, build_dir: Path | None = BUILD,
                 offsets: Path = LD2_OFFSETS, folder: str = FOLDER) -> dict[str, str]:
    """Write the zip (one folder, `folder`); returns {file name: sha256} of everything in it
    but SHA256SUMS.txt."""
    _check_shape(build_dir, export_dir)
    files = {**_program_files(program_dir, build_dir), **_model_files(export_dir),
             "INSTALL.md": _read(install_md), **_extras(extras_zip)}
    try:
        files["CLMLD2.8xv"] = appvar_8xv("CLMLD2", ld2_payload(export_dir, offsets))
    except (ValueError, OSError) as e:
        raise BundleError(f"CLMLD2.8xv: {e}") from e
    sums = {name: hashlib.sha256(data).hexdigest() for name, data in sorted(files.items())}
    files["SHA256SUMS.txt"] = "".join(f"{h}  {n}\n" for n, h in sums.items()).encode()
    out.parent.mkdir(parents=True, exist_ok=True)
    tmp = out.with_suffix(".tmp")
    with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as z:
        top = zipfile.ZipInfo(f"{folder}/", STAMP)
        top.external_attr = DIR_ATTR
        z.writestr(top, "")
        for name in sorted(files):
            info = zipfile.ZipInfo(f"{folder}/{name}", STAMP)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = FILE_ATTR
            z.writestr(info, files[name])
    shutil.move(tmp, out)
    return sums


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, default=ROOT / "dist" / "CalcLM-v2.2.zip")
    ap.add_argument("--program", type=Path, default=ROOT / "ce" / "calclm" / "bin")
    ap.add_argument("--export", type=Path, default=ROOT / "runs" / "v2" / "export")
    ap.add_argument("--install", type=Path, default=ROOT / "ce" / "calclm" / "INSTALL.md")
    ap.add_argument("--extras", type=Path, default=Path.home() / "Downloads" / "CalcLM.zip")
    ap.add_argument("--build", type=Path, default=BUILD, help="core.o and clmcode.bin")
    ap.add_argument("--offsets", type=Path, default=LD2_OFFSETS, help="checked LD2 fit")
    ap.add_argument("--folder", default=FOLDER, help="the zip's one folder")
    a = ap.parse_args(argv)
    sums = build_bundle(a.out, a.program, a.export, a.install, a.extras, a.build, a.offsets,
                        a.folder)
    for name, digest in sums.items():
        print(f"{digest}  {name}")
    print(f"{hashlib.sha256(a.out.read_bytes()).hexdigest()}  {a.out}")


if __name__ == "__main__":
    main()
