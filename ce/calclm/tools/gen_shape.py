#!/usr/bin/env python3
"""Generate ce/calclm/core/clm_shape.h from an export's model.json (shape constants only).

The calculator core is compiled for one model shape (the matvec kernels are generated per
group count G), so these dims are compile-time constants. The vocabulary size, the number of AppVars and all
tensor offsets are NOT baked in: the core reads the vocab size from the blob header, walks the
tensors at load time (INTREF.md section 6) and checks the walk against the AppVars it was given,
so any export with these dims loads (e.g. a retrained export with a larger vocab, up to
CLM_VOCAB_MAX), in either export format (1: learned positions, 2: ALiBi; clm.h).

    uv run python ce/calclm/tools/gen_shape.py runs/v0/export/model.json -o ce/calclm/core/clm_shape.h
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path


def render(meta: dict) -> str:
    cfg = meta["config"]
    if cfg["n_kv_heads"] != 1:
        raise ValueError("the core implements MQA with one KV head (SPEC v0)")
    hd = cfg["dim"] // cfg["n_heads"]
    vals = {
        "CLM_DIM": cfg["dim"],
        "CLM_LAYERS": cfg["n_layers"],
        "CLM_HEADS": cfg["n_heads"],
        "CLM_HEAD_DIM": hd,
        "CLM_HIDDEN": cfg["hidden_dim"],
        "CLM_CTX": cfg["max_seq_len"],
    }
    lines = ["/* Generated by ce/calclm/tools/gen_shape.py from model.json; do not edit. */",
             "#ifndef CLM_SHAPE_H", "#define CLM_SHAPE_H", ""]
    lines += [f"#define {k} {v}" for k, v in vals.items()]
    lines += ["", "/* runtime-sized: limits only */", "#define CLM_VOCAB_MAX 1024",
              "#define CLM_MAX_APPVARS 16", "", "#endif", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("model_json", type=Path)
    ap.add_argument("-o", "--output", type=Path, required=True)
    args = ap.parse_args(argv)
    text = render(json.loads(args.model_json.read_text()))
    if not args.output.exists() or args.output.read_text() != text:
        args.output.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
