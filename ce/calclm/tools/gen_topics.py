#!/usr/bin/env python3
"""Generate ce/calclm/src/topics.h: CalcLM v2.5's topic menu (PHASE3-topic-menu.md 2d), from
model/topics.py (the candidates, their openings, check lines and section 1b's menu rule) and
the measurement fixture model.topics.FIXTURE (numbers only; v2.6: topics_v2.6.json).

Per menu entry, in menu order: the opening's token ids, the label, the rate and time texts and
the check line; plus the vocab hash the ids are for (clm_mask_ids.h's MASK_VOCAB_HASH, which the
program compares with CLMVOC), the first 6 bytes of the measured export's sha256 (CLMVOC's
export sha) and the measured LD2 fit's 16 offsets E: topics run only on the model and with the
offsets they were measured with.

    uv run python ce/calclm/tools/gen_topics.py [--fixture F] [-o src/topics.h]
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
OUT = HERE.parent / "src" / "topics.h"
VOCAB = ROOT / "corpus" / "vocab.json"


def _c_string(s: str) -> str:
    if not all(0x20 <= ord(c) < 0x7F for c in s) or '"' in s or "\\" in s:
        raise ValueError(f"menu text must be plain printable ASCII: {s!r}")
    return f'"{s}"'


def _fit_for(fx: dict) -> Path:
    """The LD2 fit the measurement records (its offsets_sha256), among the committed fits."""
    import hashlib
    for p in sorted((ROOT / "ce" / "tests" / "fixtures").glob("ld2_offsets_*.json")):
        if hashlib.sha256(p.read_bytes()).hexdigest() == fx["offsets_sha256"]:
            return p
    raise ValueError(f"no committed LD2 fit has sha256 {fx['offsets_sha256']}")


def render(fx: dict, fixture: Path | None = None) -> str:
    """topics.h for the measurement fx, loaded from `fixture` (default model.topics.FIXTURE)."""
    sys.path.insert(0, str(ROOT))
    from ce.calclm.tools.gen_mask_ids import vocab_hash
    from model import topics as TP
    vocab = json.loads(VOCAB.read_text())
    entries = TP.menu_entries(fx)
    topics, random = entries[:-1], entries[-1]
    ids, start = [], [0]
    for e in topics:
        ids += TP.prompt(e["key"])
        start.append(len(ids))
    if any(not 4 <= t < len(vocab) for t in ids) or len(ids) > 0xFFFF:
        raise ValueError("opening ids outside the vocab")
    for e in topics:
        if len(e["label"]) > 20 or len(TP.check_line(e["key"])) > 40:
            raise ValueError(f"{e['key']}: menu text too long")
    sha6 = bytes.fromhex(fx["export_sha256"])[:6]
    fit = _fit_for(fx)                                              # the measured LD2 fit
    E = json.loads(fit.read_text())["E"]
    h = vocab_hash(b"" if h.startswith("<") else bytes.fromhex(h) for h in vocab)
    arr = lambda t, name, xs: [f"static const {t} {name}[{len(xs)}] = {{",  # noqa: E731
                               *("    " + ", ".join(str(x) for x in xs[i:i + 12]) + ","
                                 for i in range(0, len(xs), 12)), "};"]
    strs = lambda name, xs: [f"static const char *const {name}[TOPIC_N] = {{",  # noqa: E731
                             *(f"    {_c_string(x)}," for x in xs), "};"]
    lines = [
        "/* Generated by ce/calclm/tools/gen_topics.py from model/topics.py and",
        f" * ce/tests/fixtures/{Path(fixture or TP.FIXTURE).name} (PHASE3-topic-menu.md); "
        "do not edit.",
        f" * Menu: {', '.join(e['key'] for e in topics)}, then Random. Measured on export",
        f" * {fx['export_sha256'][:16]}..., seeds {fx['seeds'][0]}-{fx['seeds'][1]}, k "
        f"{next(iter(fx['topics'].values()))['k']} per topic, cap {fx['cap']}, mask level "
        f"{fx['mask_level']}, seed mix {fx['seed_mix']}. */",
        "#ifndef CALCLM_TOPICS_H", "#define CALCLM_TOPICS_H", "", "#include <stdint.h>", "",
        f"#define TOPIC_N {len(topics)}",
        f"#define TOPIC_VOCAB {len(vocab)}",
        f"#define TOPIC_VOCAB_HASH 0x{h:08x}UL     /* = clm_mask_ids.h MASK_VOCAB_HASH */",
        "#define TOPIC_EXPORT_SHA \"" + "".join(f"\\x{b:02x}" for b in sha6)
        + "\"   /* CLMVOC's 6-byte export sha */",
        f"#define TOPIC_CAP {TP.CAP}",
        f"#define TOPIC_TEMP_Q8 {TP.TEMPERATURE_Q8}",
        f"#define TOPIC_TOP_K {TP.TOP_K}",
        f"#define TOPIC_MASKS {TP.MASK_LEVEL}",
        f"#define RANDOM_LABEL {_c_string(random['label'])}",
        f"#define RANDOM_RATE {_c_string(random['rate'])}",
        f"#define RANDOM_TIME {_c_string(random['time'])}", "",
        "/* the openings, back to back; entry i is topic_ids[topic_start[i] .. topic_start[i+1]) */",
        *arr("uint16_t", "topic_ids", ids),
        *arr("uint16_t", "topic_start", start),
        "/* the measured LD2 fit's offsets E (the accepted CLMLD2 must carry these) */",
        *arr("uint32_t", "topic_ld2_E", E),
        *strs("topic_label", [e["label"] for e in topics]),
        *strs("topic_rate", [e["rate"] for e in topics]),
        *strs("topic_time", [e["time"] for e in topics]),
        *strs("topic_check", [TP.check_line(e["key"]) for e in topics]),
        "", "#endif", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--fixture", type=Path, default=None)
    ap.add_argument("-o", "--out", type=Path, default=OUT)
    a = ap.parse_args(argv)
    sys.path.insert(0, str(ROOT))
    from model import topics as TP
    fixture = a.fixture or TP.FIXTURE
    a.out.write_text(render(TP.load_fixture(fixture), fixture))
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
