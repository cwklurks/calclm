#!/usr/bin/env python3
"""Generate ce/calclm/core/clm_mask_ids.h: the token ids the logit masks use (INTREF.md 13,
model/intmask.py mask_ids), for the vocab the tracker's class table was generated from
(tracker/trk_tables.h, corpus/vocab.json by default), and a hash of that vocab's token bytes
that the calculator checks against CLMVOC before it allows the masks (src/model.c).

    uv run python ce/calclm/tools/gen_mask_ids.py [--vocab corpus/vocab.json] [-o core/clm_mask_ids.h]
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
VOCAB = ROOT / "corpus" / "vocab.json"
OUT = HERE.parent / "core" / "clm_mask_ids.h"


def vocab_hash(token_bytes) -> int:
    """FNV-1a (32 bits) over every id's token byte count and bytes, in id order (CLMVOC's
    record order; the specials have no bytes)."""
    h = 0x811C9DC5
    for b in token_bytes:
        for x in bytes([len(b)]) + bytes(b):
            h = ((h ^ x) * 0x01000193) & 0xFFFFFFFF
    return h


def level2(ids: dict) -> list[str]:
    """Mask level 2 (v2.4, model/safety.py): the always-banned ids, the window variables and
    the ids of the statements that assign them, the string classes (sorted ids, class each)
    and the string automaton (next state per class, banned classes per state)."""
    from model import safety as S
    assert len(ids["str_ids"]) <= 255 and len(S.STR_NEXT) <= 255 and S.N_CLASSES <= 16
    assert all(not (b >> S.C_W) & 1 for b in S.STR_BAN), "the C walk skips class W ids"
    arr = lambda t, name, xs: [f"static const {t} {name}[{len(xs)}] = {{",  # noqa: E731
                               *("    " + ", ".join(str(x) for x in xs[i:i + 12]) + ","
                                 for i in range(0, len(xs), 12)), "};"]
    nb = (ids["vocab"] + 7) // 8

    def bits(xs):
        b = [0] * nb
        for x in xs:
            b[x >> 3] |= 1 << (x & 7)
        return b
    out = ["", "/* level 2 (v2.4 safety masks, model/safety.py) */",
           f"#define MASK_BAN_BYTES {nb}",
           f"#define MASK_N_STR {len(ids['str_ids'])}",
           f"#define MASK_STR_START {S.STR_START}",
           f"#define MASK_QUOTE {ids['quote']}", f"#define MASK_PLUS {ids['plus']}", ""]
    out += arr("uint8_t", "MASK_ALWAYS_BITS", bits(ids["always"]))   # calls, setting commands
    out += arr("uint8_t", "MASK_WINDOW_BITS", bits(ids["window"]))   # the 63xx variables
    out += arr("uint16_t", "MASK_LOOPVAR", ids["loopvar"])   # For( IS>( DS<(
    out += arr("uint16_t", "MASK_IO", ids["io"])             # Input Prompt
    out += arr("uint16_t", "MASK_STR_IDS", ids["str_ids"])   # ids whose class is not W, sorted
    out += arr("uint8_t", "MASK_STR_CLS", ids["str_cls"])
    out += [f"static const uint8_t MASK_STR_NEXT[{len(S.STR_NEXT)}][{S.N_CLASSES}] = {{",
            *("    {" + ", ".join(str(x) for x in row) + "}," for row in S.STR_NEXT), "};"]
    out += arr("uint16_t", "MASK_STR_BAN", S.STR_BAN)       # bit c: class c is banned
    return out


def render(vocab: list[str]) -> str:
    sys.path.insert(0, str(ROOT))
    from model.intmask import mask_ids

    ids = mask_ids(vocab)
    vh = vocab_hash(b"" if h.startswith("<") else bytes.fromhex(h) for h in vocab)
    arr = lambda name, xs: [f"static const uint16_t {name}[{len(xs)}] = {{",  # noqa: E731
                            *("    " + ", ".join(str(x) for x in xs[i:i + 12]) + ","
                              for i in range(0, len(xs), 12)), "};"]
    lines = ["/* Generated by ce/calclm/tools/gen_mask_ids.py from the vocab list: do not edit. */",
             "#ifndef CLM_MASK_IDS_H", "#define CLM_MASK_IDS_H", "", "#include <stdint.h>", "",
             f"#define MASK_VOCAB {len(vocab)}",
             f"#define MASK_VOCAB_HASH {vh:#010x}UL",
             f"#define MASK_END {ids['end']}", f"#define MASK_ELSE {ids['else']}",
             f"#define MASK_NEWLINE {ids['newline']}", f"#define MASK_LISTL {ids['listl']}",
             f"#define MASK_N_SAFETY {len(ids['safety'])}", f"#define MASK_N_VARS {len(ids['vars'])}",
             f"#define MASK_N_NAMES {len(ids['names'])}", ""]
    lines += arr("MASK_SAFETY", ids["safety"])      # DelVar ClrAllLists Archive UnArchive ClrList
    lines += arr("MASK_VARS", ids["vars"])          # Str1..Str0, [A]..[J]
    lines += arr("MASK_PENDING", ids["pending"])    # , (
    lines += arr("MASK_NAMES", ids["names"])        # A-Z 0-9 theta (the hint bit order)
    lines += level2(ids | {"vocab": len(vocab)})
    lines += ["", "#endif", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--vocab", type=Path, default=VOCAB)
    ap.add_argument("-o", "--output", type=Path, default=OUT)
    args = ap.parse_args(argv)
    vocab = json.loads(args.vocab.read_text())
    if isinstance(vocab, dict):                      # an export's model.json embeds the list
        vocab = vocab["vocab"]
    text = render(vocab)
    if not args.output.exists() or args.output.read_text() != text:
        args.output.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
