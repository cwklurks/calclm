# ---- T1: the default and W builds equal the recorded baseline (v2.5 since phase 3) -----------

@_CEDEV
@pytest.mark.parametrize("tag", ["", "w"], ids=["default", "w"])
def test_t1_core_builds_are_byte_identical(tag):
    build_core(force=True, tag=tag)
    base, o = BASELINE[tag or "default"], out_dir(tag)
    av = CALCLM / "bin" / tag / "CLMCODE.8xv" if tag else CALCLM / "bin" / "CLMCODE.8xv"
    assert _sha(o / "test.bin") == base["test.bin"]
    assert _sha(o / "clmcode.bin") == base["clmcode.bin"]
    assert _sha(av) == base["CLMCODE.8xv"]
    assert (o / "obj" / "code_id").read_text().strip() == base["code_id"]
    if str(ROOT) == BASELINE["built_in"]:
        assert _sha(o / "core.o") == base["core.o"]


def _make(*args: str) -> None:
    env = dict(os.environ, PATH=f"{CEDEV}:{os.environ['PATH']}")
    subprocess.run(["make", *args], cwd=CALCLM, env=env, check=True, capture_output=True)


@_CEDEV
def test_t1_programs_are_identical_outside_the_build_stamp():
    """`make` and `make SHAPE=w` from clean objects: CALCLM.8xp equal outside bytes 11..52."""
    shutil.rmtree(CALCLM / "obj", ignore_errors=True)
    for tag in ("", "w"):
        _make(*([f"SHAPE={tag}"] if tag else []))
        prog = CALCLM / "bin" / tag / "CALCLM.8xp" if tag else CALCLM / "bin" / "CALCLM.8xp"
        assert _unstamped(prog) == BASELINE[tag or "default"]["CALCLM.8xp_unstamped"]


# ---- T2, host part: the CLMKV4 payload ---------------------------------------------------------

@_RUNS
def test_t2_make_kv4_round_trips_the_stored_tables():
    from ce.calclm.tools.make_kv4 import HEADER, parse, payload, payload_size
    from model.kv4 import read_tables
    data = payload(W8, KV4 / "W8-s10.json")
    t = read_tables(KV4 / "W8-s10.json", W8)
    meta = json.loads((W8 / "model.json").read_text())
    assert len(data) == payload_size(8) == HEADER + 1024 + 8192
    got = parse(data)
    assert (got["layers"], got["head_dim"]) == (8, 32)
    assert got["sha6"] == meta["sha256"][:12]
    assert got["blob_bytes"] == meta["blob_bytes"]
    np.testing.assert_array_equal(got["M"], t.m)
    np.testing.assert_array_equal(got["T"], t.t)
    assert (got["pad"] == 0x80).all()


@_RUNS
def test_t2_make_kv4_refuses_another_exports_tables():
    from ce.calclm.tools.make_kv4 import payload
    with pytest.raises(ValueError, match="refuses"):
        payload(W8_S11, KV4 / "W8-s10.json")
    with pytest.raises(ValueError):
        payload(L4, KV4 / "W8-s10.json")


@_RUNS
def test_t2_clmkv4_fits_one_appvar():
    from ce.calclm.tools.build_flash import appvar_8xv
    from ce.calclm.tools.make_kv4 import payload
    data = payload(W8, KV4 / "W8-s10.json")
    av = appvar_8xv("CLMKV4", data)
    assert av[74:74 + int.from_bytes(av[72:74], "little")] == data
    assert len(data) <= 65505


# ---- step P: the CE program for W8 at 4-bit ----------------------------------------------------

BSS_LIMIT = 0xD13FD8 - 0xD052C6        # 60,690 B: the toolchain's BSS region


@_CEDEV
def test_p_w8k4_program_builds_and_fits():
    """`make SHAPE=w8k4`: bin/w8k4/CALCLM.8xp links the w8k4 core.o; its BSS (the packed K
    cache, 38,912 B, and the rest) fits the toolchain's region; bin/w8k4/CLMCODE.8xv carries the
    payload the w8k4 emulator tests attach."""
    _make("SHAPE=w8k4")
    prog = CALCLM / "bin" / "w8k4" / "CALCLM.8xp"
    assert prog.exists() and prog.stat().st_size <= 60000
    mp = (CALCLM / "bin" / "w8k4" / "CALCLM.map").read_text()
    bss = int(mp.split("___bss_len = (___bss_high - ___bss_low)")[0].split()[-1], 16)
    assert bss <= BSS_LIMIT
    assert bss >= 8 * 256 * 19
    av = (CALCLM / "bin" / "w8k4" / "CLMCODE.8xv").read_bytes()
    payload = (out_dir("w8k4") / "clmcode.bin").read_bytes()
    assert av[74:74 + int.from_bytes(av[72:74], "little")] == payload
