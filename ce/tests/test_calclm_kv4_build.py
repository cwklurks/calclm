from ce.tools.clm import CALCLM, CORE_DIR, ROOT, build_core, out_dir

FIXTURES = Path(__file__).parent / "fixtures"
BASELINE = json.loads((FIXTURES / "e20_t1_baseline.json").read_text())
CEDEV = Path.home() / "CEdev" / "bin"
_CEDEV = pytest.mark.skipif(not (CEDEV / "cedev-config").exists(), reason="needs ~/CEdev")

W8 = ROOT / "runs" / "e16" / "export" / "W8-s10"
W8_S11 = ROOT / "runs" / "e16" / "export" / "W8-s11"
L4 = ROOT / "runs" / "e15" / "export" / "L4-s10"
