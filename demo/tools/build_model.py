"""Build the browser demo's model package, demo/build/calclm-model.js (git-ignored: it holds the
weights; never commit or publish it). docs/agents/phase6-browser-demo.md.

    uv run python -m demo.tools.build_model \\
        [--export runs/e24/export/L4c-s11] [--fit ce/tests/fixtures/ld2_offsets_L4c-s11.json]

The package holds what the calculator holds: the AppVar payloads CLM00.. (ce.tools.clm.Export),
the CLMLD2 payload (ce.calclm.tools.make_ld2.payload, which checks the fit against the export),
the token bytes (CLMVOC's records, for the masks' vocab check and prgmGEN's body), the text of
each token as model.intref.render shows it (tivars, TI-84 Plus CE, one token at a time), and the
menu keys of the topics (model.topics). It is a script that sets globalThis.CALCLM_MODEL, so a
page opened from file:// can load it with <script src>.
"""
from __future__ import annotations

import argparse
import base64
import json
import os
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "demo" / "build" / "calclm-model.js"
FIT = ROOT / "ce" / "tests" / "fixtures" / "ld2_offsets_L4c-s11.json"   # = model.topics.FIT
EXPORT_REL = Path("runs") / "e24" / "export" / "L4c-s11"   # the deployed model (v2.6-rc2)
PREFIX = "globalThis.CALCLM_MODEL = "
SPECIALS = 4


def default_export() -> Path | None:
    """CALCLM_DEMO_EXPORT, else runs/e24/export/L4c-s11 of this checkout, else of the main
    checkout when this is a git worktree (runs/ is not shared with worktrees)."""
    env = os.environ.get("CALCLM_DEMO_EXPORT")
    if env:
        return Path(env)
    cands = [ROOT / EXPORT_REL]
    try:
        common = subprocess.run(["git", "rev-parse", "--path-format=absolute", "--git-common-dir"],
                                cwd=ROOT, capture_output=True, text=True, check=True).stdout
        cands.append(Path(common.strip()).parent / EXPORT_REL)
    except (OSError, subprocess.CalledProcessError):
        pass
    return next((p for p in cands if (p / "model.bin").exists()), None)


def token_text(hexbytes: str) -> str:
    """One token's text as model.intref.render shows it (before render's final rstrip)."""
    from tivars import TIProgram
    prog = TIProgram(name="CALCLM")
    prog.data = bytes.fromhex(hexbytes)
    return prog.string()


def join_text(table: list[str], ids) -> str:
    """The page's detokenizer: render(m, ids) from the per-id table."""
    return "".join(table[i] for i in ids if i >= SPECIALS).rstrip("\n")


def package(export: Path, fit: Path = FIT) -> dict:
    from ce.calclm.tools.make_ld2 import payload
    from ce.tools.clm import Export
    from model import topics as TP

    ex = Export.load(export)
    ld2 = payload(export, fit)            # ValueError unless the fit and model.bin are export's
    vocab = ex.meta["vocab"]
    hexes = [""] * SPECIALS + vocab[SPECIALS:]
    return {
        "format": 1,
        "name": f"{export.parent.parent.name.upper()} {export.name}",
        "export_sha256": ex.meta["sha256"],
        "fit": fit.name,
        "appvars": [base64.b64encode(a).decode() for a in ex.appvars],
        "ld2": base64.b64encode(ld2).decode(),
        "vocab_hex": hexes,
        "vocab_text": [""] * SPECIALS + [token_text(h) for h in hexes[SPECIALS:]],
        "topic_keys": {t.label: t.key for t in TP.CANDIDATES},
    }


def write(pkg: dict, out: Path = OUT) -> Path:
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("// Generated by demo/tools/build_model.py; holds model weights. Do not commit "
                   "or publish.\n" + PREFIX + json.dumps(pkg, ensure_ascii=False) + ";\n")
    return out


def read_package(path: Path = OUT) -> dict:
    text = Path(path).read_text()
    start = text.index(PREFIX) + len(PREFIX)
    return json.loads(text[start:].rstrip().rstrip(";"))


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--export", type=Path, default=None)
    ap.add_argument("--fit", type=Path, default=FIT)
    ap.add_argument("--out", type=Path, default=OUT)
    a = ap.parse_args(argv)
    export = a.export or default_export()
    if export is None:
        raise SystemExit("no export: pass --export or set CALCLM_DEMO_EXPORT")
    out = write(package(export, a.fit), a.out)
    print(f"model package {out} ({out.stat().st_size} bytes) from {export}")


if __name__ == "__main__":
    main()
