#!/usr/bin/env bash
# Build the browser demo's WebAssembly module from the calculator's own C sources
# (docs/agents/phase6-browser-demo.md):
#
#   demo/build/calclm.wasm      the core (ce/calclm/core/*.c on its non-eZ80 path, the host
#                               matvec stand-in, tracker/tracker.c), src/menu.c's pure part and
#                               src/topics.h, demo/wasm/demo.c; no imports
#   demo/build/calclm-core.js   the same bytes as base64, for <script src> (file:// pages
#                               cannot fetch)
#
# Same files and the W shape header as the host build (ce/tools/clm.py build_host); clang's
# wasm32 target and wasm-ld, no emscripten, no libc. One file at a time (no parallel jobs).
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
DEMO="$(cd "$HERE/.." && pwd)"
ROOT="$(cd "$DEMO/.." && pwd)"
CORE="$ROOT/ce/calclm/core"
SRC="$ROOT/ce/calclm/src"
TRACKER="$ROOT/tracker"
OUT="$DEMO/build"
OBJ="$OUT/obj"
CLANG="${CLANG:-clang}"
WASM_LD="${WASM_LD:-wasm-ld}"
mkdir -p "$OBJ"

CFLAGS=(--target=wasm32 -std=c11 -O2 -ffreestanding -fno-builtin -nostdlib
        -Wall -Wextra -Werror
        -include "$CORE/clm_shape_w.h" -I"$DEMO/wasm/include" -I"$CORE" -I"$TRACKER" -I"$SRC")
SOURCES=("$CORE"/clm_int.c "$CORE"/clm_load.c "$CORE"/clm_fwd.c "$CORE"/clm_gen.c
         "$CORE"/clm_ld2.c "$CORE"/clm_ld2_load.c "$CORE"/clm_mask.c "$CORE"/clm_code.c
         "$CORE"/host/tmv_host.c "$TRACKER"/tracker.c "$SRC"/menu.c
         "$DEMO"/wasm/demo.c "$DEMO"/wasm/shim.c)

objs=()
for c in "${SOURCES[@]}"; do
    o="$OBJ/$(basename "${c%.c}").o"
    "$CLANG" "${CFLAGS[@]}" -c "$c" -o "$o"
    objs+=("$o")
done

# every demo_* function of demo.c is exported, and the linear memory
exports=()
while IFS= read -r name; do
    exports+=("--export=$name")
done < <(grep -oE '^[a-z_0-9 *]+[ *](demo_[a-z_0-9]+)\(' "$DEMO/wasm/demo.c" \
         | grep -oE 'demo_[a-z_0-9]+' | sort -u)

# the shim's memcpy/memset/memcmp/strlen must not have become calls (to themselves): they call
# nothing at all
OBJDUMP="${LLVM_OBJDUMP:-llvm-objdump}"
if command -v "$OBJDUMP" >/dev/null && "$OBJDUMP" -d "$OBJ/shim.o" | grep -qE '^\s+[0-9a-f]+:.*\bcall\b'; then
    echo "demo/wasm/shim.c compiled to code with calls (a self-recursive memcpy?)" >&2
    exit 1
fi

# --stack-first: the stack sits below the static data, so an overflow traps instead of
# overwriting the K/V caches
"$WASM_LD" --no-entry --strip-all --gc-sections --stack-first "${exports[@]}" \
    -z stack-size=262144 "${objs[@]}" -o "$OUT/calclm.wasm"

{
    echo "// Generated by demo/tools/build_wasm.sh from the calculator's C sources; do not edit."
    printf 'globalThis.CALCLM_WASM_B64 = "%s";\n' "$(base64 -w0 "$OUT/calclm.wasm")"
} > "$OUT/calclm-core.js"
echo "wasm=$OUT/calclm.wasm ($(stat -c %s "$OUT/calclm.wasm") bytes, ${#exports[@]} exports)"
